-- Controle de estoque, retiradas e histórico de cola da Cobrideira.
-- As entradas representam lotes de recebimento; cada código interno é baixado
-- uma única vez, na primeira bobina que o utiliza.

create table if not exists cobrideira.estoque_cola_entradas (
 id bigint generated by default as identity primary key,
 data_chegada date not null default current_date,
 nf text not null,
 produto text not null default 'PS-2001',
 lote text not null,
 quantidade_containers integer not null check(quantidade_containers>0),
 peso_por_container_kg numeric(12,3) not null check(peso_por_container_kg>0),
 valor_por_container numeric(14,4) not null default 0 check(valor_por_container>=0),
 valor_por_kg numeric(14,6) generated always as (case when peso_por_container_kg>0 then valor_por_container/peso_por_container_kg else 0 end) stored,
 fornecedor text not null,
 observacoes text,
 criado_em timestamptz not null default now(),
 criado_por uuid
);
create table if not exists cobrideira.estoque_cola_containers (
 codigo text primary key,
 status text not null check(status in ('DISPONIVEL','CONSUMIDO_PRODUCAO','ENVIADO_BAHIA','HISTORICO_ANTERIOR')),
 entrada_id bigint references cobrideira.estoque_cola_entradas(id) on delete set null,
 primeira_bobina text,
 primeiro_uso_em date,
 enviado_em timestamptz,
 enviado_por uuid,
 criado_em timestamptz not null default now()
);
create table if not exists cobrideira.movimentacoes_cola (
 id bigint generated by default as identity primary key,
 tipo text not null check(tipo in ('CONSUMO_PRODUCAO','RETIRADA_BAHIA','ESTORNO_CONSUMO')),
 codigo_container text,
 entrada_id bigint references cobrideira.estoque_cola_entradas(id) on delete set null,
 numero_bobina text,
 quantidade_containers integer not null default 1 check(quantidade_containers>0),
 cola_liquida_kg numeric(14,3) not null default 0 check(cola_liquida_kg>=0),
 ocorrido_em timestamptz not null default now(),
 ocorrido_por uuid,
 observacoes text
);
create table if not exists cobrideira.historico_cola_producao (
 numero_bobina text primary key,
 codigo_container text not null,
 data_producao date not null,
 cola_liquida_kg numeric(14,3) not null default 0,
 lote_cola text,
 fornecedor_cola text,
 atualizado_em timestamptz not null default now()
);
create index if not exists idx_cola_entradas_data on cobrideira.estoque_cola_entradas(data_chegada desc,id desc);
create index if not exists idx_cola_movimentos_codigo on cobrideira.movimentacoes_cola(codigo_container,ocorrido_em desc);
create index if not exists idx_cola_historico_codigo_data on cobrideira.historico_cola_producao(codigo_container,data_producao desc);

create or replace function cobrideira.alocar_entrada_cola()
returns bigint language plpgsql security definer set search_path=''
as $$
declare v_id bigint;
begin
 select e.id into v_id from cobrideira.estoque_cola_entradas e
 where e.quantidade_containers > coalesce((
  select sum(m.quantidade_containers) from cobrideira.movimentacoes_cola m
  where m.entrada_id=e.id and m.tipo in ('CONSUMO_PRODUCAO','RETIRADA_BAHIA')
 ),0)
 order by e.data_chegada,e.id for update skip locked limit 1;
 return v_id;
end; $$;

create or replace function cobrideira.sincronizar_uso_cola_producao()
returns trigger language plpgsql security definer set search_path=''
as $$
declare
 v_codigo text; v_codigo_antigo text; v_entrada bigint;
 v_container cobrideira.estoque_cola_containers%rowtype;
begin
 if tg_op='DELETE' then
  delete from cobrideira.historico_cola_producao where numero_bobina=old.numero_bobina;
  v_codigo_antigo:=nullif(btrim(old.codigo_interno),'');
  if v_codigo_antigo is not null and not exists(select 1 from cobrideira.historico_cola_producao h where h.codigo_container=v_codigo_antigo) then
   select * into v_container from cobrideira.estoque_cola_containers c where c.codigo=v_codigo_antigo for update;
   if found and v_container.status='CONSUMIDO_PRODUCAO' and v_container.entrada_id is not null then
    insert into cobrideira.movimentacoes_cola(tipo,codigo_container,entrada_id,numero_bobina,observacoes)
    values('ESTORNO_CONSUMO',v_codigo_antigo,v_container.entrada_id,old.numero_bobina,'Bobina removida da produção');
    update cobrideira.estoque_cola_containers set status='DISPONIVEL',entrada_id=null,primeira_bobina=null,primeiro_uso_em=null where codigo=v_codigo_antigo;
   end if;
  end if;
  return old;
 end if;

 v_codigo:=nullif(btrim(new.codigo_interno),'');
 insert into cobrideira.historico_cola_producao(numero_bobina,codigo_container,data_producao,cola_liquida_kg,lote_cola,fornecedor_cola,atualizado_em)
 values(new.numero_bobina,coalesce(v_codigo,''),new.data,coalesce(new.consumo_cola_liquida_kg,0),nullif(btrim(new.lote_cola),''),nullif(btrim(new.fornecedor_cola),''),now())
 on conflict(numero_bobina) do update set codigo_container=excluded.codigo_container,data_producao=excluded.data_producao,
 cola_liquida_kg=excluded.cola_liquida_kg,lote_cola=excluded.lote_cola,fornecedor_cola=excluded.fornecedor_cola,atualizado_em=now();

 if v_codigo is not null and v_codigo !~ '^0+([.]0+)?$' then
  select * into v_container from cobrideira.estoque_cola_containers c where c.codigo=v_codigo for update;
  if not found then
   v_entrada:=cobrideira.alocar_entrada_cola();
   insert into cobrideira.estoque_cola_containers(codigo,status,entrada_id,primeira_bobina,primeiro_uso_em)
   values(v_codigo,'CONSUMIDO_PRODUCAO',v_entrada,new.numero_bobina,new.data);
   if v_entrada is not null then
    insert into cobrideira.movimentacoes_cola(tipo,codigo_container,entrada_id,numero_bobina,cola_liquida_kg)
    values('CONSUMO_PRODUCAO',v_codigo,v_entrada,new.numero_bobina,greatest(coalesce(new.consumo_cola_liquida_kg,0),0));
   end if;
  elsif v_container.status='DISPONIVEL' then
   v_entrada:=coalesce(v_container.entrada_id,cobrideira.alocar_entrada_cola());
   update cobrideira.estoque_cola_containers set status='CONSUMIDO_PRODUCAO',entrada_id=v_entrada,primeira_bobina=new.numero_bobina,primeiro_uso_em=new.data where codigo=v_codigo;
   if v_entrada is not null then
    insert into cobrideira.movimentacoes_cola(tipo,codigo_container,entrada_id,numero_bobina,cola_liquida_kg)
    values('CONSUMO_PRODUCAO',v_codigo,v_entrada,new.numero_bobina,greatest(coalesce(new.consumo_cola_liquida_kg,0),0));
   end if;
  end if;
 end if;

 if tg_op='UPDATE' then
  v_codigo_antigo:=nullif(btrim(old.codigo_interno),'');
  if v_codigo_antigo is not null and v_codigo_antigo is distinct from v_codigo
     and not exists(select 1 from cobrideira.historico_cola_producao h where h.codigo_container=v_codigo_antigo) then
   select * into v_container from cobrideira.estoque_cola_containers c where c.codigo=v_codigo_antigo for update;
   if found and v_container.status='CONSUMIDO_PRODUCAO' and v_container.entrada_id is not null then
    insert into cobrideira.movimentacoes_cola(tipo,codigo_container,entrada_id,numero_bobina,observacoes)
    values('ESTORNO_CONSUMO',v_codigo_antigo,v_container.entrada_id,new.numero_bobina,'Código corrigido na produção');
    update cobrideira.estoque_cola_containers set status='DISPONIVEL',entrada_id=null,primeira_bobina=null,primeiro_uso_em=null where codigo=v_codigo_antigo;
   end if;
  end if;
 end if;
 return new;
end; $$;

drop trigger if exists trg_sincronizar_uso_cola on cobrideira.bobinas;
create trigger trg_sincronizar_uso_cola
after insert or update of codigo_interno,consumo_cola_liquida_kg,data,lote_cola,fornecedor_cola or delete
on cobrideira.bobinas for each row execute function cobrideira.sincronizar_uso_cola_producao();

create or replace function cobrideira.registrar_retirada_cola(p_codigos text[],p_user_id uuid default null)
returns jsonb language plpgsql security invoker set search_path=''
as $$
declare
 v_codigo text; v_entrada bigint; v_container cobrideira.estoque_cola_containers%rowtype;
 v_total integer:=0; v_ja text[]:=array[]::text[];
begin
 if p_codigos is null or cardinality(p_codigos)=0 then raise exception 'Informe pelo menos um código de container.'; end if;
 if cardinality(p_codigos)>500 then raise exception 'Informe no máximo 500 códigos por retirada.'; end if;
 foreach v_codigo in array p_codigos loop
  v_codigo:=nullif(btrim(v_codigo),''); if v_codigo is null then continue; end if;
  select * into v_container from cobrideira.estoque_cola_containers c where c.codigo=v_codigo for update;
  if found and v_container.status='ENVIADO_BAHIA' then v_ja:=array_append(v_ja,v_codigo); continue; end if;
  if found and v_container.status in ('CONSUMIDO_PRODUCAO','HISTORICO_ANTERIOR') then
   raise exception 'O container % já foi utilizado na produção e não pode ser enviado para Bahia.',v_codigo;
  end if;
  v_entrada:=case when found then v_container.entrada_id else null end;
  if v_entrada is null then v_entrada:=cobrideira.alocar_entrada_cola(); end if;
  insert into cobrideira.estoque_cola_containers(codigo,status,entrada_id,enviado_em,enviado_por)
  values(v_codigo,'ENVIADO_BAHIA',v_entrada,now(),p_user_id)
  on conflict(codigo) do update set status='ENVIADO_BAHIA',entrada_id=excluded.entrada_id,enviado_em=now(),enviado_por=p_user_id;
  insert into cobrideira.movimentacoes_cola(tipo,codigo_container,entrada_id,ocorrido_por)
  values('RETIRADA_BAHIA',v_codigo,v_entrada,p_user_id);
  v_total:=v_total+1;
 end loop;
 return jsonb_build_object('retirados',v_total,'ja_enviados',v_ja);
end; $$;

create or replace view cobrideira.vw_estoque_cola_saldo with(security_invoker=true) as
select e.id,e.data_chegada,e.nf,e.produto,e.lote,e.quantidade_containers,e.peso_por_container_kg,e.valor_por_container,e.valor_por_kg,e.fornecedor,
 e.quantidade_containers-coalesce((select sum(m.quantidade_containers) from cobrideira.movimentacoes_cola m where m.entrada_id=e.id and m.tipo in ('CONSUMO_PRODUCAO','RETIRADA_BAHIA')),0)::integer as containers_disponiveis
from cobrideira.estoque_cola_entradas e;
create or replace view cobrideira.vw_historico_cola with(security_invoker=true) as
select h.numero_bobina,h.codigo_container,h.data_producao,h.cola_liquida_kg,h.lote_cola,h.fornecedor_cola,c.status as status_container
from cobrideira.historico_cola_producao h left join cobrideira.estoque_cola_containers c on c.codigo=h.codigo_container;

insert into cobrideira.historico_cola_producao(numero_bobina,codigo_container,data_producao,cola_liquida_kg,lote_cola,fornecedor_cola)
select numero_bobina,coalesce(nullif(btrim(codigo_interno),''),''),data,coalesce(consumo_cola_liquida_kg,0),nullif(btrim(lote_cola),''),nullif(btrim(fornecedor_cola),'')
from cobrideira.bobinas
on conflict(numero_bobina) do update set codigo_container=excluded.codigo_container,data_producao=excluded.data_producao,cola_liquida_kg=excluded.cola_liquida_kg,lote_cola=excluded.lote_cola,fornecedor_cola=excluded.fornecedor_cola;

insert into cobrideira.estoque_cola_containers(codigo,status,primeiro_uso_em,primeira_bobina)
select distinct on (btrim(codigo_interno)) btrim(codigo_interno),'HISTORICO_ANTERIOR',
 min(data) over(partition by btrim(codigo_interno)),
 first_value(numero_bobina) over(partition by btrim(codigo_interno) order by data,numero_bobina)
from cobrideira.bobinas
where nullif(btrim(codigo_interno),'') is not null and btrim(codigo_interno) !~ '^0+([.]0+)?$'
order by btrim(codigo_interno),data,numero_bobina
on conflict(codigo) do nothing;

