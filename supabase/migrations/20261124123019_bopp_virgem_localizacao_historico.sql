create table if not exists estoque_atual.bobinas_estoque_virgem_historico (
  id bigint generated by default as identity primary key,
  bobina_id uuid not null,
  codigo text,
  acao text not null check (acao in ('ENTRADA', 'ALTERACAO', 'EXCLUSAO')),
  ocorrido_em timestamptz not null default now(),
  ator_id uuid,
  ator_email text,
  dados_anteriores jsonb,
  dados_novos jsonb
);

create index if not exists bobinas_estoque_virgem_historico_bobina_idx
  on estoque_atual.bobinas_estoque_virgem_historico (bobina_id, ocorrido_em desc);

create index if not exists bobinas_estoque_virgem_historico_ocorrido_idx
  on estoque_atual.bobinas_estoque_virgem_historico (ocorrido_em desc);

alter table estoque_atual.bobinas_estoque_virgem_historico enable row level security;

create or replace function estoque_atual.registrar_historico_bobina_virgem()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  cabecalhos jsonb := coalesce(nullif(current_setting('request.headers', true), '')::jsonb, '{}'::jsonb);
  ator text := nullif(cabecalhos ->> 'x-app-actor-id', '');
  email text := nullif(cabecalhos ->> 'x-app-actor-email', '');
begin
  if tg_op = 'INSERT' then
    insert into estoque_atual.bobinas_estoque_virgem_historico
      (bobina_id, codigo, acao, ator_id, ator_email, dados_novos)
    values
      (new.id, new.codigo, 'ENTRADA', ator::uuid, email, to_jsonb(new));
    return new;
  elsif tg_op = 'UPDATE' then
    insert into estoque_atual.bobinas_estoque_virgem_historico
      (bobina_id, codigo, acao, ator_id, ator_email, dados_anteriores, dados_novos)
    values
      (new.id, new.codigo, 'ALTERACAO', ator::uuid, email, to_jsonb(old), to_jsonb(new));
    return new;
  else
    insert into estoque_atual.bobinas_estoque_virgem_historico
      (bobina_id, codigo, acao, ator_id, ator_email, dados_anteriores)
    values
      (old.id, old.codigo, 'EXCLUSAO', ator::uuid, email, to_jsonb(old));
    return old;
  end if;
end;
$$;

drop trigger if exists trg_historico_bobina_virgem
  on estoque_atual.bobinas_estoque_virgem;

create trigger trg_historico_bobina_virgem
after insert or update or delete on estoque_atual.bobinas_estoque_virgem
for each row execute function estoque_atual.registrar_historico_bobina_virgem();

