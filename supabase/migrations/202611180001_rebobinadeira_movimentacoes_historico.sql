create or replace view rebobinadeira.vw_saldo_bobinas
with (security_invoker = true)
as
with saldo_ativo as (
  select
    c.numero_bobina,
    c.data,
    c.material,
    c.largura as largura_mm,
    c.micragem,
    c.metragem as metragem_inicial_m,
    c.peso_liquido as peso_inicial_kg,
    coalesce(sum(m.metragem_delta_m), 0)::numeric(14,2) as saldo_metros,
    coalesce(sum(m.peso_delta_kg), 0)::numeric(14,3) as saldo_kg,
    coalesce(bool_or(m.tipo_movimento = 'CONSUMO'), false) as teve_consumo,
    coalesce(bool_or(m.tipo_movimento = 'DEVOLUCAO'), false) as teve_devolucao
  from cobrideira.bobinas c
  left join rebobinadeira.movimentacoes_bobinas m
    on m.numero_normalizado = rebobinadeira.normaliza_numero(c.numero_bobina)
  group by c.numero_bobina, c.data, c.material, c.largura, c.micragem, c.metragem, c.peso_liquido
),
saldo_lixeira as (
  select
    l.numero_bobina,
    nullif(l.dados->>'data','')::date as data,
    l.dados->>'material' as material,
    nullif(l.dados->>'largura','')::numeric as largura_mm,
    nullif(l.dados->>'micragem','')::integer as micragem,
    nullif(l.dados->>'metragem','')::numeric as metragem_inicial_m,
    nullif(l.dados->>'peso_liquido','')::numeric as peso_inicial_kg,
    coalesce(sum(m.metragem_delta_m), 0)::numeric(14,2) as saldo_metros,
    coalesce(sum(m.peso_delta_kg), 0)::numeric(14,3) as saldo_kg,
    coalesce(bool_or(m.tipo_movimento = 'CONSUMO'), false) as teve_consumo,
    coalesce(bool_or(m.tipo_movimento = 'DEVOLUCAO'), false) as teve_devolucao
  from cobrideira.bobinas_lixeira l
  left join rebobinadeira.movimentacoes_bobinas m
    on m.numero_normalizado = rebobinadeira.normaliza_numero(l.numero_bobina)
  where not exists (
    select 1 from cobrideira.bobinas c
    where c.numero_bobina = l.numero_bobina
  )
  group by l.numero_bobina, l.dados
)
select
  s.numero_bobina, s.data, s.material, s.largura_mm, s.micragem,
  s.metragem_inicial_m, s.peso_inicial_kg, s.saldo_metros, s.saldo_kg,
  case
    when s.saldo_metros <= coalesce((select tolerancia_metros from rebobinadeira.configuracoes_bobinas where id=1),10) then 'CONSUMIDA'
    when not s.teve_consumo then 'CADASTRADA'
    when s.teve_devolucao or s.teve_consumo then 'DEVOLVIDA_PARCIAL'
    else 'EM_USO'
  end as status
from saldo_ativo s
union all
select
  s.numero_bobina, s.data, s.material, s.largura_mm, s.micragem,
  s.metragem_inicial_m, s.peso_inicial_kg, s.saldo_metros, s.saldo_kg,
  'LIXEIRA'::text as status
from saldo_lixeira s;

