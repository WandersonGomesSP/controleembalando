create or replace function rebobinadeira.processar_consumo_producao(p_producao_id bigint)
returns void
language plpgsql
set search_path to ''
as $function$
declare
  p rebobinadeira.bobinas%rowtype;
  c cobrideira.bobinas%rowtype;
  saldo_metros numeric(14,2);
  saldo_peso numeric(14,3);
  metros_solicitados numeric(14,2);
  metros_baixados numeric(14,2);
  peso_baixado numeric(14,3);
  tolerancia numeric(8,2);
  chave text;
  tipo_alerta text;
  mensagem_alerta text;
begin
  select * into p
  from rebobinadeira.bobinas
  where id = p_producao_id
  for update;

  if not found or p.status_baixa in ('DEVOLVIDA_PARCIAL','CONSUMIDA','ESTORNADA') then
    return;
  end if;

  chave := 'CONSUMO_REBOBINADEIRA:' || p.id::text;
  if exists (
    select 1 from rebobinadeira.movimentacoes_bobinas
    where chave_origem = chave
  ) then
    return;
  end if;

  select * into c
  from cobrideira.bobinas
  where rebobinadeira.normaliza_numero(numero_bobina) = p.numero_normalizado
  limit 1;

  if not found then
    tipo_alerta := case
      when exists (
        select 1 from cobrideira.bobinas_lixeira l
        where rebobinadeira.normaliza_numero(l.numero_bobina) = p.numero_normalizado
      ) then 'BOBINA_NA_LIXEIRA'
      else 'BOBINA_NAO_ENCONTRADA'
    end;
    mensagem_alerta := case
      when tipo_alerta = 'BOBINA_NA_LIXEIRA'
        then 'A bobina foi lançada na produção, mas está na lixeira da Cobrideira.'
      else 'A bobina foi lançada na produção, mas não foi encontrada no estoque da Cobrideira.'
    end;

    update rebobinadeira.bobinas set status_baixa = 'PENDENTE' where id = p.id;
    insert into rebobinadeira.alertas_bobinas
      (tipo, severidade, numero_bobina, numero_normalizado, producao_id, mensagem, detalhes)
    values
      (tipo_alerta, 'CRITICA', p.numero_bobina, p.numero_normalizado, p.id, mensagem_alerta,
       jsonb_build_object('data_producao', p.data, 'maquina', p.maquina, 'setup', p.setup))
    on conflict do nothing;
    return;
  end if;

  insert into rebobinadeira.movimentacoes_bobinas
    (numero_bobina, numero_normalizado, tipo_movimento, metragem_delta_m,
     peso_delta_kg, chave_origem, observacoes)
  values
    (c.numero_bobina, p.numero_normalizado, 'ENTRADA', c.metragem,
     coalesce(c.peso_liquido, 0), 'ENTRADA_COBRIDEIRA:' || c.numero_bobina,
     'Saldo inicial importado do cadastro da Cobrideira.')
  on conflict (chave_origem) do nothing;

  metros_solicitados := coalesce(p.metragem_unica_m, p.metragem_bobina_m);
  if metros_solicitados is null or metros_solicitados <= 0 then
    update rebobinadeira.bobinas set status_baixa = 'PENDENTE' where id = p.id;
    insert into rebobinadeira.alertas_bobinas
      (tipo, severidade, numero_bobina, numero_normalizado, producao_id, mensagem, detalhes)
    values
      ('METRAGEM_NAO_INFORMADA', 'ALTA', p.numero_bobina, p.numero_normalizado, p.id,
       'A produção foi salva, mas não há metragem válida para calcular a baixa da bobina.',
       jsonb_build_object('metragem_unica_m', p.metragem_unica_m, 'metragem_bobina_m', p.metragem_bobina_m))
    on conflict do nothing;
    return;
  end if;

  select coalesce(sum(metragem_delta_m), 0), coalesce(sum(peso_delta_kg), 0)
    into saldo_metros, saldo_peso
  from rebobinadeira.movimentacoes_bobinas
  where numero_normalizado = p.numero_normalizado;

  select tolerancia_metros into tolerancia
  from rebobinadeira.configuracoes_bobinas where id = 1;
  tolerancia := coalesce(tolerancia, 10);

  if metros_solicitados > saldo_metros + tolerancia then
    update rebobinadeira.bobinas set status_baixa = 'PENDENTE' where id = p.id;
    insert into rebobinadeira.alertas_bobinas
      (tipo, severidade, numero_bobina, numero_normalizado, producao_id, mensagem, detalhes)
    values
      ('SALDO_INSUFICIENTE', 'CRITICA', p.numero_bobina, p.numero_normalizado, p.id,
       'A produção foi salva, mas a metragem lançada é maior que o saldo disponível. Nenhuma baixa foi feita.',
       jsonb_build_object('metros_solicitados', metros_solicitados, 'saldo_disponivel_m', saldo_metros,
                          'tolerancia_m', tolerancia))
    on conflict do nothing;
    return;
  end if;

  metros_baixados := least(metros_solicitados, greatest(saldo_metros, 0));
  peso_baixado := case
    when coalesce(c.metragem, 0) > 0
      then coalesce(c.peso_liquido, 0) * metros_baixados / c.metragem
    else 0
  end;
  peso_baixado := least(greatest(saldo_peso, 0), greatest(peso_baixado, 0));

  if metros_baixados <= 0 then
    update rebobinadeira.bobinas set status_baixa = 'PENDENTE' where id = p.id;
    insert into rebobinadeira.alertas_bobinas
      (tipo, severidade, numero_bobina, numero_normalizado, producao_id, mensagem, detalhes)
    values
      ('SALDO_ZERADO', 'CRITICA', p.numero_bobina, p.numero_normalizado, p.id,
       'A bobina não possui saldo disponível para esta produção.',
       jsonb_build_object('metros_solicitados', metros_solicitados, 'saldo_disponivel_m', saldo_metros))
    on conflict do nothing;
    return;
  end if;

  insert into rebobinadeira.movimentacoes_bobinas
    (numero_bobina, numero_normalizado, tipo_movimento, metragem_delta_m,
     peso_delta_kg, producao_id, chave_origem, observacoes)
  values
    (p.numero_bobina, p.numero_normalizado, 'CONSUMO', -metros_baixados,
     -peso_baixado, p.id, chave, 'Baixa gerada pelo lançamento da produção na Rebobinadeira.')
  on conflict (chave_origem) do nothing;

  update rebobinadeira.bobinas
  set metros_consumidos = metros_baixados,
      peso_consumido_kg = peso_baixado,
      status_baixa = case
        when saldo_metros - metros_baixados <= tolerancia then 'CONSUMIDA'
        else 'DEVOLVIDA_PARCIAL'
      end
  where id = p.id;

  update rebobinadeira.alertas_bobinas
  set status = 'RESOLVIDO', resolvido_em = now()
  where producao_id = p.id and status = 'ABERTO'
    and tipo in ('BOBINA_NAO_ENCONTRADA','BOBINA_NA_LIXEIRA','METRAGEM_NAO_INFORMADA','SALDO_INSUFICIENTE','SALDO_ZERADO');

  if metros_solicitados > metros_baixados then
    insert into rebobinadeira.alertas_bobinas
      (tipo, severidade, numero_bobina, numero_normalizado, producao_id, mensagem, detalhes)
    values
      ('TOLERANCIA_APLICADA', 'MEDIA', p.numero_bobina, p.numero_normalizado, p.id,
       'A diferença ficou dentro da tolerância de metragem; o saldo foi zerado sem ficar negativo.',
       jsonb_build_object('metros_solicitados', metros_solicitados, 'metros_baixados', metros_baixados,
                          'diferenca_m', metros_solicitados - metros_baixados, 'tolerancia_m', tolerancia))
    on conflict do nothing;
  end if;
end;
$function$;

create or replace function rebobinadeira.reprocessar_pendentes(p_numero_bobina text)
returns integer
language plpgsql
set search_path to ''
as $function$
declare
  registro record;
  total integer := 0;
begin
  for registro in
    select id
    from rebobinadeira.bobinas
    where numero_normalizado = rebobinadeira.normaliza_numero(p_numero_bobina)
      and status_baixa = 'PENDENTE'
    order by data, id
  loop
    perform rebobinadeira.processar_consumo_producao(registro.id);
    total := total + 1;
  end loop;
  return total;
end;
$function$;

create or replace function rebobinadeira.trg_registrar_entrada_cobrideira()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
begin
  insert into rebobinadeira.movimentacoes_bobinas
    (numero_bobina, numero_normalizado, tipo_movimento, metragem_delta_m,
     peso_delta_kg, chave_origem, observacoes)
  values
    (new.numero_bobina, rebobinadeira.normaliza_numero(new.numero_bobina), 'ENTRADA',
     new.metragem, coalesce(new.peso_liquido, 0),
     'ENTRADA_COBRIDEIRA:' || new.numero_bobina,
     'Entrada inicial originada do cadastro da Cobrideira.')
  on conflict (chave_origem) do nothing;

  perform rebobinadeira.reprocessar_pendentes(new.numero_bobina);
  return new;
end;
$function$;

create or replace function rebobinadeira.trg_ajustar_entrada_cobrideira()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
begin
  if old.metragem is distinct from new.metragem
     or old.peso_liquido is distinct from new.peso_liquido then
    insert into rebobinadeira.movimentacoes_bobinas
      (numero_bobina, numero_normalizado, tipo_movimento, metragem_delta_m,
       peso_delta_kg, chave_origem, observacoes)
    values
      (new.numero_bobina, rebobinadeira.normaliza_numero(new.numero_bobina), 'AJUSTE',
       coalesce(new.metragem, 0) - coalesce(old.metragem, 0),
       coalesce(new.peso_liquido, 0) - coalesce(old.peso_liquido, 0),
       'AJUSTE_COBRIDEIRA:' || new.numero_bobina || ':' || gen_random_uuid()::text,
       'Ajuste de metragem/peso originado de alteração no cadastro da Cobrideira.');
  end if;

  perform rebobinadeira.reprocessar_pendentes(new.numero_bobina);
  return new;
end;
$function$;

