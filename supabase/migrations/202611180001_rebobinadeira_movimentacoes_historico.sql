-- Preserva a tabela existente da Rebobinadeira e permite várias linhas por bobina.

alter table rebobinadeira.bobinas
  drop constraint if exists bobinas_numero_normalizado_key;

create index if not exists bobinas_numero_normalizado_idx
  on rebobinadeira.bobinas (numero_normalizado);

alter table rebobinadeira.bobinas
  add column if not exists linha_csv integer,
  add column if not exists hash_linha text,
  add column if not exists status_baixa text not null default 'NAO_PROCESSADA',
  add column if not exists metros_consumidos numeric(14,2),
  add column if not exists peso_consumido_kg numeric(14,3);

alter table rebobinadeira.bobinas
  drop constraint if exists bobinas_status_baixa_check;

alter table rebobinadeira.bobinas
  add constraint bobinas_status_baixa_check
  check (status_baixa in ('NAO_PROCESSADA','PENDENTE','EM_USO','DEVOLVIDA_PARCIAL','CONSUMIDA','ESTORNADA'));

alter table rebobinadeira.bobinas
  add constraint bobinas_hash_linha_key unique (hash_linha);

create table if not exists rebobinadeira.movimentacoes_bobinas (
  id bigint generated by default as identity primary key,
  numero_bobina text not null,
  numero_normalizado text not null,
  tipo_movimento text not null check (tipo_movimento in ('ENTRADA','CONSUMO','DEVOLUCAO','AJUSTE','ESTORNO')),
  metragem_delta_m numeric(14,2) not null,
  peso_delta_kg numeric(14,3) not null,
  producao_id bigint references rebobinadeira.bobinas(id) on delete restrict,
  chave_origem text not null unique,
  observacoes text,
  criado_por uuid,
  criado_em timestamptz not null default now()
);

create index if not exists movimentacoes_bobinas_numero_idx
  on rebobinadeira.movimentacoes_bobinas (numero_normalizado, criado_em);

create index if not exists movimentacoes_bobinas_producao_idx
  on rebobinadeira.movimentacoes_bobinas (producao_id);

create table if not exists rebobinadeira.alertas_bobinas (
  id bigint generated by default as identity primary key,
  tipo text not null,
  severidade text not null default 'ALTA' check (severidade in ('CRITICA','ALTA','MEDIA','BAIXA')),
  status text not null default 'ABERTO' check (status in ('ABERTO','RESOLVIDO')),
  numero_bobina text,
  numero_normalizado text,
  producao_id bigint references rebobinadeira.bobinas(id) on delete set null,
  mensagem text not null,
  detalhes jsonb not null default '{}'::jsonb,
  criado_em timestamptz not null default now(),
  resolvido_em timestamptz,
  resolvido_por uuid
);

create index if not exists alertas_bobinas_status_idx
  on rebobinadeira.alertas_bobinas (status, severidade, criado_em desc);

create index if not exists alertas_bobinas_numero_idx
  on rebobinadeira.alertas_bobinas (numero_normalizado, status);

create unique index if not exists alertas_bobinas_aberto_unique
  on rebobinadeira.alertas_bobinas (producao_id, tipo)
  where status = 'ABERTO' and producao_id is not null;

create table if not exists rebobinadeira.configuracoes_bobinas (
  id smallint primary key default 1 check (id = 1),
  tolerancia_metros numeric(8,2) not null default 10 check (tolerancia_metros >= 0),
  atualizado_em timestamptz not null default now()
);

insert into rebobinadeira.configuracoes_bobinas (id, tolerancia_metros)
values (1, 10)
on conflict (id) do nothing;

