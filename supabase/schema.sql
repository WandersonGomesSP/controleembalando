create table if not exists public.rolos (
  id text primary key,
  medida text not null,
  peso_bruto numeric(12, 3) not null check (peso_bruto > 0),
  tara numeric(12, 3) not null default 0 check (tara >= 0),
  validade text not null,
  entrada date not null default current_date,
  check (tara < peso_bruto)
);

create table if not exists public.residuos (
  id bigint generated by default as identity primary key,
  data date not null default current_date,
  origem text not null,
  peso numeric(12, 3) not null check (peso > 0),
  operador text not null
);

create table if not exists public.lotes_tubete (
  id bigint generated by default as identity primary key,
