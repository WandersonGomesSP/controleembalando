create or replace function public.dar_baixa_rolo(
  p_id text,
  p_residuo numeric,
  p_operador text default 'Operador atual'
)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  rolo public.rolos%rowtype;
begin
  select * into rolo
  from public.rolos
  where id = p_id
  for update;

  if not found then
    return false;
  end if;

  delete from public.rolos where id = p_id;

  if p_residuo > 0 then
    insert into public.residuos (data, origem, peso, operador)
    values (
      current_date,
      'Rolo ' || rolo.id || ' · ' || rolo.medida,
      p_residuo,
      p_operador
    );
  end if;

  return true;
end;
$$;

