create or replace function public.proximo_codigo_insumo(
  p_tipo text,
  p_medida_categoria text
)
returns text
language plpgsql
security invoker
set search_path = ''
as $$
declare
  prefixo text;
  sufixo text := '';
  chave_serie text;
  sequencia integer;
begin
  if not exists (
    select 1
    from public.referencias_insumos
    where tipo = p_tipo and medida_categoria = p_medida_categoria
  ) then
    raise exception 'Tipo ou categoria de insumo não cadastrada.';
  end if;

  if p_tipo = 'CAPA' then
    if p_medida_categoria = 'Capa Branca' then
      prefixo := 'B' || to_char(current_date, 'MM');
    elsif p_medida_categoria = 'Capa Marrom' then
      prefixo := 'M' || to_char(current_date, 'MM');
    else
      raise exception 'Categoria de capa inválida.';
    end if;
    chave_serie := prefixo;
  elsif p_tipo = 'ROTULO' then
    prefixo := substring(p_medida_categoria from '^([0-9]{2})');
    if prefixo is null then
      raise exception 'Categoria de rótulo inválida.';
    end if;
    if p_medida_categoria = '18mm Fix Baby' then
      sufixo := 'F';
    elsif p_medida_categoria = '19mm Hosp' then
      sufixo := 'H';
    end if;
    chave_serie := prefixo || sufixo;
  else
    raise exception 'Tipo de insumo inválido.';
  end if;

  perform pg_advisory_xact_lock(hashtext('insumo-codigo:' || chave_serie));

  select coalesce(max(substring(id_codigo from char_length(prefixo) + 1 for 2)::integer), 0) + 1
    into sequencia
  from public.insumos_rolos
  where id_codigo ~ ('^' || prefixo || '[0-9]{2}' || sufixo || '$');

  if sequencia > 99 then
    raise exception 'Sequência de dois dígitos esgotada para esta série.';
  end if;

  return prefixo || lpad(sequencia::text, 2, '0') || sufixo;
end;
$$;

create or replace function public.registrar_insumo_rolo(
  p_tipo text,
  p_medida_categoria text,
  p_peso_liq_kg numeric,
  p_validade text,
  p_id_codigo text default null
)
returns setof public.insumos_rolos
language plpgsql
security invoker
set search_path = ''
as $$
declare
  codigo text;
begin
  if not exists (
    select 1
    from public.referencias_insumos
    where tipo = p_tipo and medida_categoria = p_medida_categoria
  ) then
    raise exception 'Tipo ou categoria de insumo não cadastrada.';
  end if;

  if p_id_codigo is null or btrim(p_id_codigo) = '' then
    codigo := public.proximo_codigo_insumo(p_tipo, p_medida_categoria);
  else
    codigo := btrim(p_id_codigo);
  end if;

  return query
    insert into public.insumos_rolos
      (id_codigo, tipo, medida_categoria, peso_liq_kg, validade)
    values
      (codigo, p_tipo, p_medida_categoria, p_peso_liq_kg, p_validade)
    returning *;
end;
$$;

create or replace function public.baixar_insumo_rolo(p_id_codigo text)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  linhas integer;
begin
  update public.insumos_rolos
  set status = 'BAIXADO'
  where id_codigo = p_id_codigo and status = 'DISPONIVEL';
  get diagnostics linhas = row_count;
  return linhas = 1;
end;
$$;

