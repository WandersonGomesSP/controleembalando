create table if not exists public.rolos (
  id text primary key,
  medida text not null,
  peso_bruto numeric(12, 3) not null check (peso_bruto > 0),
  tara numeric(12, 3) not null default 0 check (tara >= 0),
  validade text not null,
  entrada date not null default current_date,
  check (tara < peso_bruto)
);

create table if not exists public.residuos (
  id bigint generated by default as identity primary key,
  data date not null default current_date,
  origem text not null,
  peso numeric(12, 3) not null check (peso > 0),
  operador text not null
);

create table if not exists public.lotes_tubete (
  id bigint generated by default as identity primary key,
  medida text not null,
  cor text not null,
  gramatura integer not null default 0 check (gramatura >= 0),
  data_producao date not null,
  caixas integer not null check (caixas > 0),
  unidades_por_caixa integer not null check (unidades_por_caixa > 0),
  perda integer not null default 0 check (perda >= 0),
  operador text not null
);

create table if not exists public.referencias_tubetes (
  descricao text primary key,
  medida text not null,
  cor text,
  tubetes_por_caixa integer not null check (tubetes_por_caixa > 0),
  estoque_min integer check (estoque_min >= 0)
);

create table if not exists public.insumos_rolos (
  id_codigo text primary key,
  tipo text not null check (tipo in ('ROTULO', 'CAPA')),
  medida_categoria text not null,
  peso_liq_kg numeric(12, 3) not null check (peso_liq_kg > 0),
  validade text not null check (validade ~ '^[0-9]{2}/[0-9]{2}$'),
  data_registro date not null default current_date,
  status text not null default 'DISPONIVEL'
    check (status in ('DISPONIVEL', 'BAIXADO'))
);

create index if not exists insumos_rolos_tipo_status_idx
  on public.insumos_rolos (tipo, status, medida_categoria);

create table if not exists public.referencias_insumos (
  tipo text not null check (tipo in ('ROTULO', 'CAPA')),
  medida_categoria text not null,
  estoque_min_kg numeric(12, 3),
  limite_critico_kg numeric(12, 3),
  primary key (tipo, medida_categoria),
  check (estoque_min_kg is null or estoque_min_kg >= 0),
  check (limite_critico_kg is null or limite_critico_kg >= 0)
);

create table if not exists public.producao_tubos (
  id bigint generated by default as identity primary key,
  destino text not null,
  data date not null,
  espessura text not null,
  tubo text not null,
  capa text not null,
  codigos jsonb not null default '{}'::jsonb,
  operador text not null,
  perda numeric(12, 3) not null default 0 check (perda >= 0),
  container text not null default '',
  carrinho text not null default ''
);

create sequence if not exists public.rolo_id_seq start with 1043;

