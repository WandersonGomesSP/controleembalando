create or replace function public.is_current_developer()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.developer_accounts
    where email = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

create or replace function public.can_access_area(p_area text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_current_developer()
    or exists (
      select 1 from public.user_roles
      where user_id = auth.uid() and role = 'ADMIN'
    )
    or exists (
      select 1 from public.user_roles
      where user_id = auth.uid() and role = 'OPERATOR' and area = p_area
    );
$$;

create or replace function public.current_user_access()
returns table (role text, area text)
language sql
stable
security definer
set search_path = ''
as $$
  select 'DEVELOPER'::text, null::text
  where public.is_current_developer()
  union all
  select roles.role, roles.area
  from public.user_roles as roles
  where roles.user_id = auth.uid()
    and not public.is_current_developer();
$$;

