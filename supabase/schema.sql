create or replace function public.is_current_developer()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.developer_accounts
    where email = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

create or replace function public.can_access_area(p_area text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_current_developer()
    or exists (
      select 1 from public.user_roles
      where user_id = auth.uid() and role = 'ADMIN'
    )
    or exists (
      select 1 from public.user_roles
      where user_id = auth.uid() and role = 'OPERATOR' and area = p_area
    );
$$;

create or replace function public.reserve_global_stock_code()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  codigo_novo text;
  codigo_antigo text;
  linhas_afetadas integer;
begin
  if TG_TABLE_NAME = 'rolos' then
    codigo_novo := NEW.id;
    if TG_OP = 'UPDATE' then codigo_antigo := OLD.id; end if;
  else
    codigo_novo := NEW.id_codigo;
    if TG_OP = 'UPDATE' then codigo_antigo := OLD.id_codigo; end if;
  end if;

  if TG_OP = 'DELETE' then
    if TG_TABLE_NAME = 'rolos' then
      delete from public.stock_code_registry
      where codigo = OLD.id and tabela_origem = TG_TABLE_NAME;
    else
      delete from public.stock_code_registry
      where codigo = OLD.id_codigo and tabela_origem = TG_TABLE_NAME;
    end if;
    return OLD;
  end if;

  if TG_OP = 'UPDATE' and codigo_antigo = codigo_novo then
    return NEW;
  end if;

  if TG_OP = 'UPDATE' then
    delete from public.stock_code_registry
    where codigo = codigo_antigo and tabela_origem = TG_TABLE_NAME;
  end if;

  insert into public.stock_code_registry as codigos_reservados
    (codigo, tabela_origem)
  values (codigo_novo, TG_TABLE_NAME)
  on conflict (codigo) do update
  set tabela_origem = excluded.tabela_origem
  where codigos_reservados.tabela_origem = excluded.tabela_origem;
  get diagnostics linhas_afetadas = row_count;
  if linhas_afetadas = 0 then
    raise exception using
      errcode = '23505',
      message = 'Código já está cadastrado em outra tabela de estoque: ' || codigo_novo;
  end if;
  return NEW;
end;
$$;

