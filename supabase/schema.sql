create or replace function public.adicionar_rolos(
  p_medida text,
  p_peso_bruto numeric,
  p_tara numeric,
  p_validade text,
  p_quantidade integer
)
returns setof public.rolos
language plpgsql
security invoker
set search_path = ''
as $$
declare
  indice integer;
begin
  if p_quantidade < 1 or p_quantidade > 99 then
    raise exception 'Quantidade de rolos inválida.';
  end if;

  for indice in 1..p_quantidade loop
    return query
      insert into public.rolos (id, medida, peso_bruto, tara, validade)
      values (
        'R-' || nextval('public.rolo_id_seq')::text,
        p_medida,
        p_peso_bruto,
        p_tara,
        p_validade
      )
      returning *;
  end loop;
end;
$$;

create or replace function public.dar_baixa_rolo(
  p_id text,
  p_residuo numeric,
  p_operador text default 'Operador atual'
)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  rolo public.rolos%rowtype;
begin
  select * into rolo
  from public.rolos
  where id = p_id
  for update;

  if not found then
    return false;
  end if;

  delete from public.rolos where id = p_id;

  if p_residuo > 0 then
    insert into public.residuos (data, origem, peso, operador)
    values (
      current_date,
      'Rolo ' || rolo.id || ' · ' || rolo.medida,
      p_residuo,
      p_operador
    );
  end if;

  return true;
end;
$$;

